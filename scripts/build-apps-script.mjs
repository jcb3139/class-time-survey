import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { currentSchedule } from "../site/schedule.js";
import { proposedSchedule } from "../site/proposed-schedule.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export async function createAppsScriptBundle() {
  const validation = (await readFile(path.join(root, "shared/survey-validation.js"), "utf8"))
    .replace(/^import .*;\n/gm, "").replace(/^export /gm, "");
  const receiver = await readFile(path.join(root, "apps-script/Receiver.gs"), "utf8");
  return '// Generated by npm run build:backend. Paste this complete file into Google Apps Script.\n' +
    'const currentSchedule = ' + JSON.stringify(currentSchedule) + ';\n' +
    'const proposedSchedule = ' + JSON.stringify(proposedSchedule) + ';\n\n' + validation + '\n' + receiver;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(path.join(root, "apps-script/Code.gs"), await createAppsScriptBundle());
  console.log("Google Apps Script backend generated at apps-script/Code.gs");
}
